// Writes docs/specs/static-catalog/v1.json: the static catalog files as an OpenAPI 3.1
// document (each file is a GET). The desktop app's contract test reads it. Commit the output;
// CI fails when it is stale.
import { writeFileSync } from "node:fs";
import { Type } from "@sinclair/typebox";
import {
  CatalogSnapshotSchema,
  GameSchema,
  PortDetailSchema,
  ReleaseSchema,
} from "../src/schema/catalog.js";

const IndexSchema = Type.Object({
  schema: Type.Literal(1),
  rev: Type.Integer({ minimum: 0 }),
  generated_at: Type.String({ format: "date-time" }),
  port_count: Type.Integer({ minimum: 0 }),
  content_hash: Type.String(),
});

const file = (summary: string, schema: unknown, params: string[] = []) => ({
  get: {
    summary,
    ...(params.length
      ? {
          parameters: params.map((name) => ({
            in: "path",
            name,
            required: true,
            schema: { type: "string" },
          })),
        }
      : {}),
    responses: {
      200: { description: "OK", content: { "application/json": { schema } } },
      404: { description: "No such file" },
    },
  },
});

const doc = {
  openapi: "3.1.0",
  info: {
    title: "Portside static catalog",
    version: "1",
    description: "docs/specs/static-catalog.md. Generated by `pnpm contract:write` in catalog/.",
  },
  paths: {
    "/v1/index.json": file("Build info", IndexSchema),
    "/v1/snapshot.json": file("Every port, summarized", CatalogSnapshotSchema),
    "/v1/ports/{id}.json": file("One port", PortDetailSchema, ["id"]),
    "/v1/ports/{id}/releases.json": file(
      "A port's releases, newest first",
      Type.Array(ReleaseSchema),
      ["id"],
    ),
    "/v1/games/{game_key}.json": file("One game and its ports", GameSchema, ["game_key"]),
  },
};

const out = new URL("../../docs/specs/static-catalog/v1.json", import.meta.url);
writeFileSync(out, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`wrote ${out.pathname}`);
